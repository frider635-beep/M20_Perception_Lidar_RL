"""RSL-RL bridge and ABI gate for the V13.2 dual-return policy."""

from __future__ import annotations

import os

from rsl_rl.runners import OnPolicyRunner


class V132DualCriticRunner(OnPolicyRunner):
    """Convert the legacy config and enforce the 68-D/dual-critic contract."""

    def __init__(self, env, train_cfg: dict, log_dir: str | None = None, device="cpu"):
        cfg = dict(train_cfg)
        task_weight = float(cfg.pop("v132_task_advantage_weight", 1.0))
        style_weight = float(cfg.pop("v132_style_advantage_weight", 1.0))
        cfg["algorithm"] = dict(cfg["algorithm"])
        cfg["algorithm"].pop("beta", None)
        cfg["algorithm"]["class_name"] = "rl_training.v132_dual_critic:V132DualCriticPPO"
        cfg["algorithm"]["style_reward_term"] = "v132_style"
        cfg["algorithm"]["task_advantage_weight"] = task_weight
        cfg["algorithm"]["style_advantage_weight"] = style_weight

        policy = dict(cfg.pop("policy"))
        if policy.pop("class_name", None) != "V132BarrierActorCritic":
            raise RuntimeError("V13.2 runner received the wrong policy configuration.")
        init_std = policy.pop("init_noise_std")
        std_type = policy.pop("noise_std_type")
        if policy.pop("state_dependent_std", False):
            raise RuntimeError("V13.2 requires state-independent log action standard deviation.")
        actor_normalization = policy.pop("actor_obs_normalization")
        critic_normalization = policy.pop("critic_obs_normalization")
        actor_hidden = policy.pop("actor_hidden_dims")
        critic_hidden = policy.pop("critic_hidden_dims")
        activation = policy.pop("activation")
        if policy.pop("include_depth_input", False):
            raise RuntimeError("V13.2 does not permit a hidden depth-image actor input.")
        if policy:
            raise RuntimeError(f"V13.2 runner received unsupported policy fields: {sorted(policy)}")

        cfg["obs_groups"] = {"actor": ["policy"], "critic": ["critic"]}
        cfg["actor"] = {
            "class_name": "rsl_rl.models:MLPModel",
            "hidden_dims": actor_hidden,
            "activation": activation,
            "obs_normalization": actor_normalization,
            "distribution_cfg": {
                "class_name": "rsl_rl.modules.distribution:GaussianDistribution",
                "init_std": init_std,
                "std_type": std_type,
            },
        }
        cfg["critic"] = {
            "class_name": "rsl_rl.models:MLPModel",
            "hidden_dims": critic_hidden,
            "activation": activation,
            "obs_normalization": critic_normalization,
        }
        super().__init__(env, cfg, log_dir=log_dir, device=device)

        actor = self.alg.actor
        action_dim = actor.distribution.output_dim if actor.distribution is not None else -1
        if (actor.obs_dim, action_dim) != (68, 16):
            raise RuntimeError(
                f"V13.2 actor ABI must be 68D->16D, got {actor.obs_dim}D->{action_dim}D."
            )
        if self.alg.style_critic is self.alg.critic:
            raise RuntimeError("V13.2 style and task critics must be independent objects.")
        self._write_actor_manifest(log_dir)
        print("V132_ACTOR_OBS_DIM=68", flush=True)
        print("V132_ACTION_DIM=16", flush=True)
        print("V132_TASK_STYLE_ADVANTAGE_WEIGHTS=" f"{task_weight:.3f}/{style_weight:.3f}", flush=True)
        print("V132_DUAL_CRITIC=YES", flush=True)

    @staticmethod
    def _write_actor_manifest(log_dir: str | None) -> None:
        if log_dir is None:
            return
        os.makedirs(log_dir, exist_ok=True)
        with open(os.path.join(log_dir, "actor_observation_manifest.txt"), "w", encoding="ascii") as stream:
            stream.write(
                "M20 V13.2 actor observation (68D)\\n"
                "0:3 base_ang_vel; 3:6 projected_gravity; 6:9 command; "
                "9:25 joint_pos; 25:41 joint_vel; 41:57 previous_action; "
                "57 B1; 58 H1; 59 D1; 60 B2; 61 H2; 62 D2; "
                "63 expected_side(-1 FL,0 unset,+1 FR); "
                "64:68 phase_one_hot(approach,alternating,top_follow,plateau)\\n"
                "The five phase values are generated by the deployable PGTT/kinematic hysteresis ledger.\\n"
            )


__all__ = ["V132DualCriticRunner"]
